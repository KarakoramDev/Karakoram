// CPUpgradeFixture is a frozen legacy control-plane snapshot, not a fixture
// regenerated from today's defaults or lock. Its credentials are disposable
// test-only identities generated by the legacy package's existing fake cluster.
// Runtime preserves the genuine old preparation commands and artifact hashes.
// Provider tests restore Services into their own infrastructure fake.
type CPUpgradeFixture struct {
	Revision    string
	Cluster     *domain.Cluster
	Secrets     map[string][]byte
	Tokens      map[string]string
	Services    []infra.Service
	Ownership   map[string]map[string]string
	Internal    json.RawMessage
	Runtime     infra.RuntimeSpec
	At          time.Time
	Configs     map[string]agentapi.MemberConfig
	Runtimes    map[string]infra.RuntimeSpec
	Executables map[string]string
}

type cpUpgradeClock struct{ at time.Time }

func (c cpUpgradeClock) Now() time.Time {
	if !c.at.IsZero() {
		return c.at
	}
	// Freeze legacy certificate validity: these tests exercise lock drift,
	// not the unrelated certificate-renewal rollout.
	return time.Date(2026, time.November, 6, 0, 0, 0, 0, time.UTC)
}

var fixtureJSONString = regexp.MustCompile(`"(?:[^"\\]|\\.)*"`)

// RestoreFixtureKeys restores the PEM label on disposable fake-cluster TLS
// identities. Frozen snapshots mark private keys as KARAKORAM TEST ONLY so
// committed fixtures cannot be mistaken for deployable credentials by secret
// scanners. The key bytes and certificate pairings are unchanged in memory.
// This transformation is deliberately confined to this test helper, including
// JSON nested inside base64-encoded Secrets entries; production never sees it.
func RestoreFixtureKeys(t *testing.T, raw []byte) []byte {
	t.Helper()
	const marker = "KARAKORAM TEST ONLY PRIVATE KEY-----"
	return fixtureJSONString.ReplaceAllFunc(raw, func(literal []byte) []byte {
		var value string
		if err := json.Unmarshal(literal, &value); err != nil {
			t.Fatal(err)
		}
		original := value
		if strings.Contains(value, marker) {
			value = strings.ReplaceAll(value, marker, "PRIVATE KEY-----")
		} else if decoded, err := base64.StdEncoding.DecodeString(value); err == nil && strings.Contains(string(decoded), marker) {
			// Preserve nested JSON bytes, including whitespace used in hashes.
			decoded = []byte(strings.ReplaceAll(string(decoded), marker, "PRIVATE KEY-----"))
			value = base64.StdEncoding.EncodeToString(decoded)
		}
		if value == original {
			return literal
		}
		replaced, err := json.Marshal(value)
		if err != nil {
			t.Fatal(err)
		}
		return replaced
	})
}

func RestoreCPUpgrade(t *testing.T, rc *engine.Context, path string) *CPUpgradeFixture {
	t.Helper()
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	var f CPUpgradeFixture
	if err = json.Unmarshal(RestoreFixtureKeys(t, raw), &f); err != nil {
		t.Fatal(err)
	}
	if f.Revision != "ed9541a6" && f.Revision != "eea8bd7" && f.Revision != "441b0639" && f.Revision != "1cb6bd98" || f.Cluster == nil || len(f.Services) == 0 || len(f.Runtime.Prepare) == 0 {
		t.Fatal("incomplete legacy CP snapshot")
	}
	rc.Cluster = f.Cluster
	rc.Cluster.Internal = f.Internal
	rc.Clock = cpUpgradeClock{at: f.At}
	for i := range f.Services {
		f.Services[i].Ownership = f.Ownership[f.Services[i].Hostname]
	}
	for key, value := range f.Secrets {
		if err = rc.Secrets.SetClusterSecret(t.Context(), rc.Cluster.Ref(), key, value); err != nil {
			t.Fatal(err)
		}
	}
	for member, value := range f.Tokens {
		token := &domain.AgentToken{Namespace: rc.Cluster.Namespace, Cluster: rc.Cluster.Name, Member: member, Token: value, Hash: secrets.Hash(value)}
		if err = rc.Secrets.SetAgentToken(t.Context(), token); err != nil {
			t.Fatal(err)
		}
	}
	return &f
}
