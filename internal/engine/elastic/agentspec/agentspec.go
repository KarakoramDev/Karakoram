// Package agentspec defines the Elasticsearch engine payload carried in
// agentapi.MemberConfig.EngineSpec. It is shared by the control-plane provider
// (internal/engine/elastic) and the node-agent runner (internal/agent/elastic)
// and must stay dependency-free. The payload contains secrets; agents cache it
// with owner-only permissions like the rest of MemberConfig.
package agentspec

// Engine is the MemberConfig.Engine value and KARAKORAM_ENGINE environment value.
const Engine = "elasticsearch"

// Component values select which Elastic Stack product a member runs.
const (
	ComponentElasticsearch = "elasticsearch"
	ComponentKibana        = "kibana"
	ComponentLogstash      = "logstash"
	ComponentAPM           = "apm-server"
)

// Well-known private ports.
const (
	PortHTTP          = 9200
	PortTransport     = 9300
	PortKibana        = 5601
	PortLogstashAPI   = 9600
	PortLogstashBeats = 5044
	PortLogstashHTTP  = 8080
	PortAPM           = 8200
	PortAPMMonitoring = 5066
)

// InstallRoot is where run.prepareCommands extract official tarballs.
const InstallRoot = "/opt/elastic"

// Home returns the extracted product directory for a component and version.
func Home(component, version string) string {
	switch component {
	case ComponentKibana:
		return InstallRoot + "/kibana-" + version
	case ComponentLogstash:
		return InstallRoot + "/logstash-" + version
	case ComponentAPM:
		return InstallRoot + "/apm-server-" + version + "-linux-x86_64"
	default:
		return InstallRoot + "/elasticsearch-" + version
	}
}

// Product returns the artifact product name used in artifacts.elastic.co URLs.
func Product(component string) string {
	if component == ComponentAPM {
		return "apm-server"
	}
	return component
}

// Certificate is a PEM leaf certificate and its private key.
type Certificate struct {
	CertPEM string `json:"certPEM"`
	KeyPEM  string `json:"keyPEM"`
}

// Credentials is a username/password pair.
type Credentials struct {
	Username string `json:"username"`
	Password string `json:"password"`
}

// Pipeline is one Logstash pipeline definition.
type Pipeline struct {
	ID     string `json:"id"`
	Config string `json:"config"`
}

// Spec is the Elasticsearch engine payload for one member.
type Spec struct {
	// Component selects the product run by this member.
	Component string `json:"component"`
	// Version is the exact Elastic Stack version installed under Home().
	Version string `json:"version"`
	// HeapMB is the JVM heap for Elasticsearch/Logstash (Xms=Xmx) and the
	// Node.js --max-old-space-size for Kibana. Zero leaves product defaults.
	HeapMB int `json:"heapMB,omitempty"`
	// CAPEM is the cluster CA; Elasticsearch HTTP/transport trust and every
	// component's trust for Elasticsearch HTTPS.
	CAPEM string `json:"caPEM"`
	// RestartToken is an opaque digest. The agent restarts the product process
	// only when it changes; other file updates are hot-reloaded.
	RestartToken string `json:"restartToken"`

	Elasticsearch *ElasticsearchSpec `json:"elasticsearch,omitempty"`
	Kibana        *KibanaSpec        `json:"kibana,omitempty"`
	Logstash      *LogstashSpec      `json:"logstash,omitempty"`
	APM           *APMSpec           `json:"apm,omitempty"`
}

// Readiness is a live local application observation, not just process liveness.
type Readiness struct {
	Component          string `json:"component"`
	Ready              bool   `json:"ready"`
	Message            string `json:"message,omitempty"`
	ConfigurationError bool   `json:"configurationError,omitempty"`
	ConfigVersion      int64  `json:"configVersion"`
}

// ElasticsearchSpec configures one Elasticsearch node.
type ElasticsearchSpec struct {
	ClusterName string   `json:"clusterName"`
	NodeName    string   `json:"nodeName"`
	Roles       []string `json:"roles"`
	// SeedHosts are master-eligible "host:9300" entries rendered into the
	// hot-reloaded unicast_hosts.txt file seed provider.
	SeedHosts []string `json:"seedHosts"`
	// InitialMasterNodes is set only until the cluster UUID has been observed.
	InitialMasterNodes []string    `json:"initialMasterNodes,omitempty"`
	TransportCert      Certificate `json:"transportCert"`
	HTTPCert           Certificate `json:"httpCert"`
	// FileUsers, FileUsersRoles and FileRoles are the complete contents of the
	// file-realm `users`, `users_roles` and `roles.yml` files (hot-reloaded).
	FileUsers      string `json:"fileUsers"`
	FileUsersRoles string `json:"fileUsersRoles"`
	FileRoles      string `json:"fileRoles"`
	// SecureSettings are keystore entries (e.g. s3.client.<name>.access_key).
	SecureSettings map[string]string `json:"secureSettings,omitempty"`
	// Settings are additional elasticsearch.yml entries generated by the
	// provider (S3 client endpoint/region/path style, validated user overrides).
	Settings map[string]any `json:"settings,omitempty"`
	// Monitor is the file-realm monitoring identity used by the agent's
	// metrics exporter against the local node.
	Monitor Credentials `json:"monitor"`
}

// KibanaSpec configures Kibana.
type KibanaSpec struct {
	ESHosts             []string `json:"esHosts"`
	ServiceAccountToken string   `json:"serviceAccountToken"`
	// EncryptionKeys: security, encryptedSavedObjects, reporting (each >= 32 chars).
	SecurityKey     string         `json:"securityKey"`
	SavedObjectsKey string         `json:"savedObjectsKey"`
	ReportingKey    string         `json:"reportingKey"`
	PublicBaseURL   string         `json:"publicBaseURL,omitempty"`
	Settings        map[string]any `json:"settings,omitempty"`
}

// LogstashSpec configures Logstash.
type LogstashSpec struct {
	ESHosts   []string    `json:"esHosts"`
	Writer    Credentials `json:"writer"`
	Pipelines []Pipeline  `json:"pipelines,omitempty"`
	// PersistentQueue enables queue.type persisted on the member data dir.
	PersistentQueue bool `json:"persistentQueue"`
}

// APMSpec configures APM Server.
type APMSpec struct {
	ESHosts     []string    `json:"esHosts"`
	Writer      Credentials `json:"writer"`
	SecretToken string      `json:"secretToken"`
	// APIKeys enables agent API-key authentication.
	APIKeys bool `json:"apiKeys"`
}
